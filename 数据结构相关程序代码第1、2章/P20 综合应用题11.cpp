// 11.【2011统考真题】一个长度为L(L≥1)的升序序列S，处在第[L/2]个位置的数称为S的中位数。
// 例如，若序列S1=(11,13,15,17,19)，则S1的中位数是15，两个序列的中位数是含它们所有元素的升序序列的中位数。
// 例如，若S2=(2,4,6,8,20)，则S1和S2的中位数是11。
// 现在有两个等长升序序列A和B，试设计一个在时间和空间两方面都尽可能高效的算法，找出两个序列A和B的中位数。要求：
// (1)给出算法的基本设计思想。
