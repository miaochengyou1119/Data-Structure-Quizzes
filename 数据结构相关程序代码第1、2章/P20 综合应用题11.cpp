// (3)说明你所设计算法的时间复杂度和空间复杂度。

// (1)算法的基本设计思想如下。
// ①若a=b，则a或b为所求中位数，算法结束。
// ②若a<b，则舍弃序列A中较小的一半，同时舍弃序列B中较大的一半，要求两次舍弃的长度相等。
// ③若a>b，则舍弃序列A中较大的一半，同时舍弃序列B中较小的一半，要求两次舍弃的长度相等。
// 在保留的两个升序序列中，重复过程①、②、③，直到两个序列中均只含一个元素时为止，较小者为所求的中位数。

// (2)本题代码如下：

#include<stdio.h>

int M_Search(int A[], int B[], int n) {
	int s1, d1, m1, s2, d2, m2;
	s1 = 0; d1 = n - 1;
	s2 = 0; d2 = n - 1;
	while (s1 != d1 || s2 != d2) {
		m1 = (s1 + d1) / 2;
		m2 = (s2 + d2) / 2;
		if (A[m1] == B[m2])
			return A[m1]; // 满足条件①
		if (A[m1] < B[m2]) { // 满足条件②
			if ((s1 + d1) % 2 == 0) { // 若元素个数为奇数
				s1 = m1; // 舍弃A中间点以前的部分，且保留中间点
				d2 = m2; // 舍弃B中间点以后的部分，且保留中间点
			}
			else { // 元素个数为偶数
				s1 = m1 + 1; // 舍弃A的前半部分
				d2 = m2; // 舍弃B的后半部分
			}
		}
		else { // 满足条件③
			if ((s1 + d1) % 2 == 0) { // 若元素个数为奇数
				d1 = m1; // 舍弃A中间点以后的部分，且保留中间点
				s2 = m2; // 舍弃B中间点以前的部分，且保留中间点
			}
			else { // 元素个数为偶数
				d1 = m1; // 舍弃A的后半部分
				s2 = m2 + 1; // 舍弃B的前半部分
			}
		}
	}
	return A[s1] < B[s2] ? A[s1] : B[s2];
}

