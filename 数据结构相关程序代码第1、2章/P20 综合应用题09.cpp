// 9.给定三个序列A、B、C，长度均为n，且均为无重复元素的递增序列，请设计一个时间上尽可能高效的算法，逐行输出同时存在于这三个序列中的所有元素。
// 例如，数组A为{1,2,3}，数组B为{2,3,4}，数组C为{-1,0,2}，则输出2。
// 要求：
// (1)给出算法的基本设计思想。
// (2)根据设计思想，采用C或者C++语言描述算法，关键之处给出注释。
// (3)说明你的算法的时间复杂度和空间复杂度。

// (1)算法的基本设计思想：使用三个下标变量从小到大遍历数组。
// 当三个下标变量指向的元素相等时，输出并向前推进指针，否则仅移动小于最大元素的下标变量，直到某个下标变量移出数组范围，即可停止。

// (2)算法的实现。

#include<stdio.h>

// 补充max函数实现（用于求三个数的最大值）
int max(int a, int b, int c) {
	int temp = a > b ? a : b;
	return temp > c ? temp : c;
}

void samekey(int A[], int B[], int C[], int n) {
	int i = 0, j = 0, k = 0; // 定义三个工作指针
	while (i < n && j < n && k < n) {
		if (A[i] == B[j] && B[j] == C[k]) {
			printf("%d\n", A[i]);
			i++;
			j++;
			k++;
		} else {
			int maxNum = max(A[i], B[j], C[k]);
			if (A[i] < maxNum)i++;
			if (B[j] < maxNum)j++;
			if (C[k] < maxNum)k++;
		}
	}
}

// 主函数：用于测试算法的完整运行逻辑
int main() {
	// 示例测试用例（对应题目中的示例）
	int A[] = { 1,2,3 };
	int B[] = { 2,3,4 };
	int C[] = { -1,0,2};
	int n = 3; // 三个序列的长度均为n
	// 调用函数输出共同元素
	samekey(A, B, C, n);
	return 0;
}

// (3)每个指针移动的次数不超过n，且每次循环至少有一个指针后移，故时间复杂度为O(n)，算法只用到了常数个变量，空间复杂度为O(1)。